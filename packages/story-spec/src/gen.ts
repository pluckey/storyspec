// spec.md → scenarios.gen.ts, so tests written with story() must cover exactly the spec's scenarios.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { isTypeScript, type Story } from './trace/scan.js'

export const GEN_FILE = 'scenarios.gen.ts'

const HEADER = '// Generated by `story-spec gen` from spec.md. Do not edit.'
// The header releases before the rename wrote. A file that differs only there is still fresh, so a project keeps
// passing its check until `story-spec migrate` rewrites it.
const OLD_HEADER = '// Generated by `storyspec gen` from spec.md. Do not edit.'

const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

export const renderGen = (story: Story) => {
  // A scenario proven only locally stays a plain title, so projects that never declare tiers see no change.
  const lines = story.scenarios.map(s => s.proof.length === 1 && s.proof[0] === 'local'
    ? `    ${quote(s.id)}: ${quote(s.title || s.id)},`
    : `    ${quote(s.id)}: { title: ${quote(s.title || s.id)}, proof: [${s.proof.map(quote).join(', ')}] },`)
  return [
    HEADER,
    'export const gen = {',
    `  storyId: ${quote(story.id)},`,
    `  title: ${quote(story.front.title ?? '')},`,
    '  scenarios: {',
    ...lines,
    '  },',
    '} as const',
    '',
    'export type ScenarioId = keyof typeof gen.scenarios',
    '',
  ].join('\n')
}

/** `oldName`: fresh, but written before the rename (its header names the old command). */
export type GenStatus = { story: string; file: string; state: 'fresh' | 'stale' | 'missing'; oldName?: true }

// The generated file types TypeScript tests. A story with TypeScript in its folder gets one; so does one with nothing
// there yet in a TypeScript project (tsconfig.json at the root, or TypeScript in any story's folder), whose use case is
// still to be written. A story implemented elsewhere (implementedBy:), or in a project that isn't TypeScript (Swift,
// Python), has nothing to type.
const typed = (s: Story, tsProject: boolean) =>
  [...s.code, ...s.tests].some(f => isTypeScript(f.path)) || (tsProject && s.implementedBy.length === 0)

export const genStatus = (root: string, stories: Story[]): GenStatus[] =>
  stories.filter(s => s.hasSpecMd && typed(s, existsSync(join(root, 'tsconfig.json'))
    || stories.some(x => [...x.code, ...x.tests].some(f => isTypeScript(f.path))))).map(s => {
    const file = join(s.dir, GEN_FILE)
    const abs = join(root, file)
    if (!existsSync(abs)) return { story: s.id, file, state: 'missing' as const }
    const text = readFileSync(abs, 'utf8'), want = renderGen(s)
    if (text === want) return { story: s.id, file, state: 'fresh' as const }
    if (text === want.replace(HEADER, OLD_HEADER)) return { story: s.id, file, state: 'fresh' as const, oldName: true as const }
    return { story: s.id, file, state: 'stale' as const }
  })

export const writeGen = (root: string, stories: Story[]) =>
  genStatus(root, stories).filter(g => g.state !== 'fresh').map(g => {
    const story = stories.find(s => s.id === g.story)!
    writeFileSync(join(root, g.file), renderGen(story))
    return g
  })

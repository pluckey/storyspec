// story-spec checks its own stories (stories/) with the last published release, not with this build: a regression in
// the trace can't then vouch for itself. The release is installed into .story-spec/released (npm's cache makes it
// quick), separate from the workspace, so `story-spec` in the template still runs this build.
//
// The release is `story-spec` once it is on npm. Until then it is the last release under the old name, `storyspec`,
// which reads `storyspec.config.json` and `.storyspec/`: for the run they are links to the renamed ones, and the one
// place the old checker writes its own name into what it compares (the header of scenarios.gen.ts) reads `story-spec`
// in its installed copy. Its rules are untouched.
//
// STORY_SPEC_CHECKER=<name>@<version> pins the checker (storyspec@0.8.0, say). --plan prints which release it would use
// and what it would give it, and runs nothing. STORY_SPEC_PUBLISHED (names, comma-separated) stands in for asking npm,
// for the test of this script.
import { execSync } from 'node:child_process'
import { existsSync, lstatSync, readdirSync, readFileSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const repo = resolve(import.meta.dirname, '..')
const dir = join(repo, '.story-spec/released')
const sh = (cmd, cwd = repo) => execSync(cmd, { cwd, stdio: 'inherit' })

const NEW = 'story-spec', OLD = 'storyspec'
const LINKS = [['storyspec.config.json', 'story-spec.config.json'], ['.storyspec', '.story-spec']]
const OLD_HEADER = '// Generated by `storyspec gen` from spec.md. Do not edit.'
const NEW_HEADER = '// Generated by `story-spec gen` from spec.md. Do not edit.'

/** The newest published version of `name`, or undefined when npm has none (or can't be reached). */
const published = (name) => {
  if (process.env.STORY_SPEC_PUBLISHED !== undefined)
    return process.env.STORY_SPEC_PUBLISHED.split(',').includes(name) ? 'latest' : undefined
  try { return execSync(`npm view ${name}@latest version`, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() || undefined } catch { return undefined }
}
const installed = (name) => { try { return JSON.parse(readFileSync(join(dir, 'node_modules', name, 'package.json'), 'utf8')).version } catch { return undefined } }

// story-spec when it is published; else the old name. Offline, whichever is already installed (the new name first).
const pick = () => {
  const pinned = /^(story-?spec)@(.+)$/.exec(process.env.STORY_SPEC_CHECKER ?? '')
  if (pinned) return { name: pinned[1], version: pinned[2] }
  for (const name of [NEW, OLD]) { const version = published(name); if (version) return { name, version } }
  for (const name of [NEW, OLD]) { const version = installed(name); if (version) return { name, version } }
  throw new Error(`Neither ${NEW} nor ${OLD} is on npm or installed in ${dir}`)
}

const checker = pick()
const old = checker.name === OLD
if (process.argv.includes('--plan')) {
  console.log(JSON.stringify({ checker: checker.name, dir: '.story-spec/released', links: old ? LINKS.map(([from]) => from) : [], header: old }))
  process.exit(0)
}

if (installed(checker.name) !== checker.version) {
  rmSync(dir, { recursive: true, force: true })
  sh(`npm install --silent --no-audit --no-fund --prefix ${dir} ${checker.name}@${checker.version} vitest`)
}
const pkg = join(dir, 'node_modules', checker.name)
const cli = join(pkg, 'dist/cli.js')
if (!existsSync(cli)) throw new Error(`${checker.name} did not install`)

if (old) {
  // Exactly one header, in the chunk the CLI shares with the library; anything else is a release this doesn't know.
  const files = readdirSync(join(pkg, 'dist')).filter(f => f.endsWith('.js')).map(f => join(pkg, 'dist', f))
  const hits = files.filter(f => readFileSync(f, 'utf8').includes(OLD_HEADER))
  const done = files.filter(f => readFileSync(f, 'utf8').includes(NEW_HEADER))
  if (hits.length === 1) writeFileSync(hits[0], readFileSync(hits[0], 'utf8').replace(OLD_HEADER, NEW_HEADER))
  else if (done.length !== 1) throw new Error(`${checker.name} ${checker.version}: expected one generated-file header in its dist, found ${hits.length}`)
}

const isLink = (p) => { try { return lstatSync(p).isSymbolicLink() } catch { return false } }
const made = []
try {
  if (old) for (const [from, to] of LINKS) {
    const at = join(repo, from)
    if (isLink(at)) unlinkSync(at)
    if (existsSync(at)) throw new Error(`${from} exists; run npx story-spec migrate, or remove it`)
    symlinkSync(to, at)
    made.push(at)
  }
  console.log(`Checking story-spec's own stories with ${checker.name} ${installed(checker.name)} (published)${old ? ', reading the renamed files through links' : ''}`)
  sh('npx tsc -p .')
  sh(`node ${cli} check`)
} finally {
  for (const at of made) if (isLink(at)) unlinkSync(at)
}
